import assert from 'node:assert/strict';
import {consultation} from '../src/lib/consultation.mjs';
const u=content=>({role:'user',content});const a=content=>({role:'assistant',content});
let messages=[u('gw batuk nih pake apa?')];let step=consultation(messages);assert.match(step.reply,/usia/i);assert.equal(step.ready,false);
messages.push(a(step.reply),u('untuk saya, 25 tahun'));step=consultation(messages);assert.match(step.reply,/berapa lama/i);
messages.push(a(step.reply),u('2 hari'));step=consultation(messages);assert.match(step.reply,/kering|berdahak/);
messages.push(a(step.reply),u('kering'));step=consultation(messages);assert.match(step.reply,/sesak/);
messages.push(a(step.reply),u('tidak ada'));step=consultation(messages);assert.match(step.reply,/alergi/);
messages.push(a(step.reply),u('tidak ada'));step=consultation(messages);assert.equal(step.ready,true);
assert.equal(consultation([u('saya 25 tahun batuk kering 2 minggu')]).blocked,true);
assert.equal(consultation([u('anak saya 4 tahun batuk 2 hari')]).blocked,true);
assert.equal(consultation([u('saya batuk dan sesak napas')]).blocked,true);
assert.match(consultation([u('saya 25 tahun batuk 2 hari'),a('Ada sesak napas, nyeri dada, batuk berdarah, atau demam tinggi?'),u('tidak ada')]).reply,/kering|berdahak/);
assert.equal(consultation([u('Apa komposisi MecoVit GO?')]),null);
assert.equal(consultation([...messages,u('sekarang untuk anak saya 3 tahun batuk')]).blocked,true);
